    def yr(s):
        import re
        s = str(s).replace(' ', '')
        m = re.search(r'前(\d+)世纪', s)
        if m: return -(int(m.group(1)) - 0.5) * 100
        m = re.search(r'(\d+)世纪', s)
        if m: return int(m.group(1)) * 100 - 50
        m = re.search(r'前(\d+)年', s)
        if m: return -int(m.group(1))
        m = re.search(r'(\d{3,4})年', s)
        if m: return int(m.group(1))
        return 0
